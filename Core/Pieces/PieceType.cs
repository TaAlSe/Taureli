namespace Core.Pieces;

/// <summary>
/// Типы таврелей (фигур) в русских шахматах.
/// </summary>
public enum PieceType
{
    /// <summary> Волхв (король) — ходит на 1 клетку в любом направлении, нельзя под шах. </summary>
    Volkhv,
    /// <summary> Всадник (конь) — ходит буквой «Г», перепрыгивает. </summary>
    Horseman,
    /// <summary> Хелги — ходит как князь + всадник. Самая сильная фигура. </summary>
    Helgi,
    /// <summary> Князь (ферзь) — ходит по вертикали, горизонтали, диагонали. </summary>
    Knyaz,
    /// <summary> Ратоборец (ладья) — ходит по вертикали и горизонтали. </summary>
    Ratoborets,
    /// <summary> Лучник (слон) — ходит по диагонали. </summary>
    Archer,
    /// <summary> Ратник (пешка) — сложные правила: первый ход на 2, бьёт диагональю, превращение. </summary>
    Ratnik
}